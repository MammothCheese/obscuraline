"""Mechanica Obscura: integer tables the chip cannot compute itself (no FPU).
Writes firmware/gen/mo_tables.h:
  MO_SIN[1024]   one sine cycle, Q15 (angle 0..65535 -> index angle >> 6)
  MO_NOTE[128]   phase increment per frame at 44.1 kHz for MIDI notes 0..127 (f * 2^32 / 44100)
  MO_ATAN[257]   atan(i/256) as a 16-bit angle (0..8192 = 0..45 degrees), for mo_atan2
"""
import math
from pathlib import Path

FS = 44100
out = []
out.append("/* SPDX-License-Identifier: GPL-3.0-only */")
out.append("/* generated by tools/gen_mo_tables.py: do not edit */")
out.append("#pragma once")
sin = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
out.append("static const int16_t MO_SIN[1024] = {")
for i in range(0, 1024, 16):
    out.append("    " + ", ".join(str(v) for v in sin[i:i + 16]) + ",")
out.append("};")
inc = [round(440 * 2 ** ((n - 69) / 12) * 2 ** 32 / FS) for n in range(128)]
out.append("static const uint32_t MO_NOTE[128] = {")
for i in range(0, 128, 8):
    out.append("    " + ", ".join(f"{v}u" for v in inc[i:i + 8]) + ",")
out.append("};")
at = [round(math.atan(i / 256) / (2 * math.pi) * 65536) for i in range(257)]
out.append("static const uint16_t MO_ATAN[257] = {")
for i in range(0, 257, 16):
    out.append("    " + ", ".join(str(v) for v in at[i:i + 16]) + ",")
out.append("};")
Path(__file__).resolve().parent.parent.joinpath("firmware/gen/mo_tables.h").write_text("\n".join(out) + "\n")
print("firmware/gen/mo_tables.h written")
